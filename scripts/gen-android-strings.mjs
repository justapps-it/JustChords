// Generates the Android app's texts from the web app, so both say the same:
// src/i18n.ts → ui/I18n.kt, src/components/Legal.tsx → ui/LegalText.kt,
// src/lib/courses.json → assets/courses.json.
// Run: node scripts/gen-android-strings.mjs
import fs from 'fs';

const OUT = 'android/app/src/main/java/it/justapps/justchords/ui';
const q = (s) => JSON.stringify(s).replace(/\$/g, '\\$');

function grab(src, name, scope = {}) {
  const start = src.indexOf(`const ${name}`);
  const open = src.indexOf('{', src.indexOf('=', start));
  const end = src.indexOf('\n};', open);
  return Function(...Object.keys(scope), `return (${src.slice(open, end + 2)})`)(...Object.values(scope));
}

const i18n = fs.readFileSync('src/i18n.ts', 'utf8');
const it = grab(i18n, 'it');
const en = grab(i18n, 'en');
let out = `package it.justapps.justchords.ui\n\n// Generated by scripts/gen-android-strings.mjs from the web app's src/i18n.ts. Do not edit.\n\nobject I18n {\n`;
for (const [n, o] of [['it', it], ['en', en]]) {
  out += `    val ${n}: Map<String, String> = hashMapOf(\n`;
  for (const [k, v] of Object.entries(o)) out += `        ${q(k)} to ${q(v)},\n`;
  out += `    )\n`;
}
fs.writeFileSync(`${OUT}/I18n.kt`, out + '}\n');

const legal = fs.readFileSync('src/components/Legal.tsx', 'utf8');
const TERMS_VERSION = fs.readFileSync('src/api.ts', 'utf8').match(/TERMS_VERSION = '([^']+)'/)[1];
const REPO = legal.match(/const REPO = '([^']+)'/)[1];
const CONTACT = legal.match(/const CONTACT = '([^']+)'/)[1];
const scope = { TERMS_VERSION, REPO, CONTACT };
const docs = { privacy: grab(legal, 'PRIVACY', scope), terms: grab(legal, 'TERMS', scope) };
let lo = `package it.justapps.justchords.ui\n\n// Generated by scripts/gen-android-strings.mjs from the web app's Legal.tsx. Do not edit.\n\nclass LegalDoc(val title: String, val sections: List<Pair<String, List<String>>>)\n\nobject LegalText {\n`;
for (const [name, d] of Object.entries(docs)) {
  lo += `    val ${name}: Map<String, LegalDoc> = mapOf(\n`;
  for (const lang of ['it', 'en']) {
    lo += `        ${q(lang)} to LegalDoc(\n            ${q(d[lang].title)},\n            listOf(\n`;
    for (const [h, ps] of d[lang].sections) lo += `                ${q(h)} to listOf(${ps.map(q).join(', ')}),\n`;
    lo += `            ),\n        ),\n`;
  }
  lo += `    )\n`;
}
fs.writeFileSync(`${OUT}/LegalText.kt`, lo + '}\n');
// Courses for "Impara": the same JSON, as an asset.
fs.mkdirSync('android/app/src/main/assets', { recursive: true });
fs.copyFileSync('src/lib/courses.json', 'android/app/src/main/assets/courses.json');
console.log(Object.keys(it).length, 'strings, legal docs, courses ok');
